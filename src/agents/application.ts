export interface ApplicationDocs {
  jobId: string;
  slug: string;
  dir: string; // absolute path to Jobs/Applications/<slug>
  resumeFile: string;
  coverFile: string;
  jobFile: string;
  tailored: boolean; // false = ollama unavailable, master copy written
  reviewed: boolean; // true = passed the proofread/cleanup step
}

const OPPORTUNITIES_FILE = path.join(vault.jobsDir, "Job Opportunities.md");

const slugify = (s: string) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60);

/**
 * Application agent: for one job the user marked Interested, generate a tailored
 * resume + cover letter with the local Ollama model and write them, plus a job
 * detail file, into Career/Jobs/Applications/<slug>/. Also appends a linked entry
 * to Career/Jobs/Job Opportunities.md.
 */
/** The tailored resume + cover-letter markdown for a job, with generation flags. */
export interface TailoredContent {
  resumeMd: string;
  coverMd: string;
  tailored: boolean; // false = Ollama offline, master copy (still truthful, now with metrics)
  reviewed: boolean; // true = passed the proofread/cleanup step
}

/**
 * Produce the tailored resume + cover-letter markdown for a job. Pure: reads the profile,
 * drives Ollama, returns markdown — writes nothing to disk. Exported so it can be driven
 * directly for previews/tests without touching the vault; applicationAgent wraps it to write.
 */
/** Options for the tailoring pass. */
export interface TailorOptions {
  /**
   * Refuse to fall back to untailored master copies when Ollama is down; throw instead.
   *
   * The fallback exists so a preview or a script can still produce truthful documents with
   * no model available. It is the wrong behaviour for the real workflow: an untailored
   * application still lands in "Application Ready", which reads as finished work and is
   * not. Callers driving the user-facing flow pass this.
   */
  requireLlm?: boolean;
}

export async function buildTailoredDocs(
  job: Job,
  profile: Profile,
  score?: Score,
  taskId?: string,
  opts: TailorOptions = {},
): Promise<TailoredContent> {
  // Contact header is built deterministically from the master frontmatter so the
  // model can never hallucinate "[Your Name]" / "[Your Phone Number]" placeholders.
  const master = matter(profile.resumeMaster || "");
  const contactHeader = buildContactHeader(master.data);
  const masterBody = stripMasterHeader(master.content);
  // JD signal (target title + the skills the scorer matched/flagged) used to re-focus
  // the skills section and re-order highlight bullets toward this specific job.
  const hints = jdHints(job, score);

  if (opts.requireLlm) await requireOllama("Tailoring this application");
  const tailored = await ollamaAvailable();
  log(tailored ? "info" : "warn",
    tailored ? "Ollama online — tailoring summary + cover letter" : "Ollama offline — writing truthful master copies (not tailored)");

  // RESUME — built deterministically from the master, never free-form generated by the
  // local model (the 7B/14B model drops sections, invents skills, and emits "[Your Name]"
  // placeholders). The model only SELECTS and ORDERS existing master content (which skill
  // categories are relevant, what order the highlight bullets go in) and rewrites the one
  // Professional Summary paragraph. Everything shipped is verbatim master text reassembled
  // by code, so the resume stays complete, truthful, and placeholder-free — but now focused
  // on this specific job instead of identical on every application.
  let tailoredSummary = "";
  let coverRaw = "";
  let workingBody = masterBody;
  if (tailored) {
    // Re-focus the skills wall to the job's relevant categories, and surface the most
    // relevant highlight bullets first. Each step self-guards: on any doubt it returns
    // the master section unchanged, so tailoring can only improve focus, never lose facts.
    if (taskId) advanceTask(taskId, 0);
    workingBody = await focusSkills(job, workingBody, hints);
    if (taskId) advanceTask(taskId, 1);
    workingBody = await reorderBulletSection(workingBody, "Career Highlights", job, hints);
    if (taskId) advanceTask(taskId, 2);
    try {
      tailoredSummary = await tailorSummary(job, workingBody);
      log("info", "✓ Professional summary re-angled to this job");
    } catch (e) {
      tailoredSummary = ""; // fall back to the master's own summary
      log("warn", `Summary tailoring rejected (${errMsg(e)}) — keeping master summary`);
    }
    if (taskId) advanceTask(taskId, 3);
    // A cancel between the two documents is the one place we can honour it without abandoning
    // a model call mid-flight: the summary is already written, the cover letter has not started.
    if (taskId && isCancelled(taskId)) {
      log("warn", "Tailoring cancelled — keeping the summary, skipping the cover letter");
      const partial = assembleResume(workingBody, ukSpelling(sanitizeText(tailoredSummary)));
      return {
        resumeMd: asciiOnly(`${contactHeader}\n\n${sanitizeText(partial)}`).trim(),
        coverMd: asciiOnly(buildFallbackCover(job, master.data, profile.coverFallback)).trim(),
        tailored,
        reviewed: false,
      };
    }
    try {
      coverRaw = await tailorCover(job, profile);
      log("info", "✓ Cover letter drafted by local model");
    } catch (e) {
      coverRaw = "";
      log("warn", `Cover letter generation failed (${errMsg(e)}) — using deterministic fallback`);
    }
  }
  const resumeBody = assembleResume(workingBody, ukSpelling(sanitizeText(tailoredSummary)));
  // asciiOnly again over the joined document: the contact header comes straight from the
  // master frontmatter, which sanitizeText never sees.
  const resumeMd = asciiOnly(`${contactHeader}\n\n${sanitizeText(resumeBody)}`).trim();

  // COVER LETTER — the model writes it, but we ship it only if it invents no tech and uses
  // no cliché tells. Otherwise (or when Ollama is off) we use a clean, truthful deterministic
  // letter built from the master facts. Either way the result is trustworthy.
  const coverGrounding = `${profile.resumeMaster}\n${profile.skills}\n${profile.experience}`;
  const modelCover = ukSpelling(sanitizeText(fillPlaceholders(coverRaw, job, master.data)));
  // 2026 length guidance: a 250-400 word body is preferred. Allow slack for the address block;
  // reject a letter that's too thin (<150 words) or bloated (>500 words) → deterministic fallback.
  const coverWords = modelCover.split(/\s+/).filter(Boolean).length;
  const coverFailed = coverRaw.trim().length ? failedGuards(modelCover, coverGrounding) : ["no-draft"];
  if (coverWords < 150) coverFailed.push(`too-short (${coverWords}w)`);
  if (coverWords > 500) coverFailed.push(`too-long (${coverWords}w)`);
  const coverOk = coverFailed.length === 0;
  // The fallback letter interpolates scraped job/company text, so ASCII-fold either branch.
  const coverMd = asciiOnly(coverOk ? modelCover : buildFallbackCover(job, master.data, profile.coverFallback)).trim();
  log("info", coverOk
    ? "Cover letter: using tailored draft (grounded + clean)"
    : `Cover letter: using deterministic fallback (draft tripped ${coverFailed.join(", ")})`);

  // The resume is verbatim master text (already clean); the deterministic cover is clean too,
  // so the job can advance to "Application Ready" whenever the model was available.
  return { resumeMd, coverMd, tailored, reviewed: tailored };
}

export async function applicationAgent(
  job: Job,
  score?: Score,
  taskId?: string,
  opts: TailorOptions = {},
): Promise<ApplicationDocs> {
  log("info", `Tailoring application — "${job.title}"${job.company ? ` @ ${job.company}` : ""}`);
  const profile = await loadProfile();
  const slug = `${slugify(job.company || job.source)}-${slugify(job.title)}`;
  const dir = path.join(vault.applicationsDir, slug);
  await fs.mkdir(dir, { recursive: true });
  log("debug", `Application folder: ${dir}`);

  const { resumeMd, coverMd, tailored, reviewed } = await buildTailoredDocs(job, profile, score, taskId, opts);

  const resumeFile = path.join(dir, "resume.md");
  const coverFile = path.join(dir, "cover-letter.md");
  const jobFile = path.join(dir, "job.md");

  await fs.writeFile(jobFile, jobDetailDoc(job, score), "utf8");
  await fs.writeFile(resumeFile, frontmatter(job, "tailored-resume") + resumeMd, "utf8");
  await fs.writeFile(coverFile, frontmatter(job, "cover-letter") + coverMd, "utf8");
  log("info", `Wrote resume.md, cover-letter.md, job.md → ${dir}`);

  await appendOpportunity(job, score, slug, tailored);
  log("debug", "Linked entry appended to Job Opportunities.md");

  return { jobId: job.id, slug, dir, resumeFile, coverFile, jobFile, tailored, reviewed };
}

/**
 * Fold every non-ASCII character down to a plain-ASCII equivalent.
 *
 * Application documents must be 7-bit ASCII end to end. Em dashes, curly quotes and middots
 * render fine in Word but break in ATS parsers, plain-text paste boxes and older recruiter
 * mail clients, so nothing sent to an employer may contain them. Characters with no sensible
 * ASCII equivalent are dropped rather than left to turn into mojibake downstream.
 */
export function asciiOnly(s: string): string {
  return (
    s
      // Decompose accents (e.g. "é" -> "e" + combining acute) so the marks can be stripped.
      .normalize("NFKD")
      .replace(/[̀-ͯ]/g, "") // combining diacritics
      // En/em dashes are almost always sentence punctuation ("Jenkins — tools I've used"),
      // so they fold to a SPACED hyphen. Folding them bare would glue the words either side
      // into a false compound ("Jenkins-tools"), which is what a reader actually sees.
      // Confined to spaces/tabs so a dash at the start of a line can't swallow the newline.
      .replace(/[ \t]*[–—][ \t]*/g, " - ")
      .replace(/[‐-‒―−⁃]/g, "-") // true hyphens, horizontal bar, minus
      .replace(/[‘’‚‛′]/g, "'") // curly single quotes, prime
      .replace(/[“”„‟″]/g, '"') // curly double quotes
      .replace(/…/g, "...") // ellipsis
      .replace(/[·•‧●▪◦]/g, "-") // middot / bullet glyphs
      .replace(/[\u00a0\u1680\u2000-\u200a\u202f\u205f\u3000]/g, " ") // exotic spaces
      .replace(/[\u200b-\u200d\u2060\ufeff]/g, "") // zero-width joiners + BOM
      .replace(/®/g, "(R)")
      .replace(/©/g, "(c)")
      .replace(/™/g, "(TM)")
      .replace(/°/g, " degrees")
      .replace(/½/g, "1/2")
      .replace(/×/g, "x")
      .replace(/[←-⇿➔-➿]/g, "->") // arrows
      // Anything still outside printable 7-bit ASCII (emoji, CJK, stray symbols) has no safe
      // equivalent — drop it rather than ship a glyph the reader's tooling may mangle.
      // eslint-disable-next-line no-control-regex -- \x09/\x0A are range endpoints we keep
      .replace(/[^\x09\x0a\x20-\x7e]/g, "")
      // Collapse the double spaces a dropped glyph leaves behind, but never touch leading
      // indentation — that would flatten nested markdown bullets.
      .replace(/(?<=\S)[ \t]{2,}/g, " ")
  );
}

/** Deterministic cleanup of common encoding garbage + control characters, then ASCII-folded. */
function sanitizeText(s: string): string {
  // Mojibake repair runs BEFORE the ASCII fold: the broken sequences are themselves
  // non-ASCII, so folding first would shred them into unrecoverable garbage.
  const repaired = s
    .normalize("NFC")
    // Reasoning models (e.g. qwen3) emit a <think>…</think> block before the answer — drop it.
    .replace(/<think>[\s\S]*?<\/think>/gi, "")
    .replace(/```[a-zA-Z]*\n?/g, "") // strip ```markdown / ``` code fences the model wraps output in
    .replace(/```/g, "")
    // eslint-disable-next-line no-irregular-whitespace -- the literal is a BOM we deliberately strip
    .replace(/﻿/g, "") // BOM
    .replace(/â€™|â€˜/g, "'")
    .replace(/â€œ|â€/g, '"')
    .replace(/â€”/g, "—")
    .replace(/â€“/g, "–")
    .replace(/Â /g, " ")
    .replace(/Ã©/g, "e");

  return asciiOnly(repaired)
    // eslint-disable-next-line no-control-regex -- deliberately matching control chars to strip them
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, "") // strip control chars (keep \n, \t)
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim()
    // Strip stray leading/trailing horizontal-rule fences the model sometimes wraps a
    // whole document in (e.g. the cover letter dressed up like a --- frontmatter block).
    .replace(/^(?:(?:-{3,}|\*{3,}|_{3,})[ \t]*\n+)+/, "")
    .replace(/\n+[ \t]*(?:-{3,}|\*{3,}|_{3,})[ \t]*$/, "")
    .trim();
}

