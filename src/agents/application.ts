// Matched on word boundaries, not as raw substrings: a bare `includes("java")` fires on
// "javascript" (which the candidate does have) and `includes("react")` misses nothing but
// also fires on "reacted". Whitespace inside a term is loosened so "spring  boot" and a
// line-wrapped "google\ncloud" still match.
const RISKY_TECH_RE: RegExp[] = RISKY_TECH.map(
  (term) => new RegExp(`\\b${escapeRe(term).replace(/ /g, "\\s+")}\\b`, "i"),
);
// AI/cliché tells we refuse to ship. Kept in sync with the "never use" list in COVER_SYS.
const BANNED_PHRASES = [
  "honed", "passionate", "excited to", "excited about", "thrilled", "leverage", "synergy",
  "delve", "tapestry", "proven track record", "results-driven", "fast-paced", "spearheaded",
  "i am writing to express", "i am confident that",
  // 2026 AI tells
  "hit the ground running", "wealth of experience", "meaningful impact", "eager to contribute",
  "perfect fit", "cutting-edge", "seamlessly", "align perfectly", "resonate",
];

// Vague scale words that read as hard evidence to a recruiter but are almost never in the
// source material. The model reaches for these to make a real achievement sound bigger
// ("pipelines that handled millions of records daily" when the profile says no such thing).
const SCALE_WORDS = [
  "millions", "billions", "thousands", "hundreds", "petabyte", "terabyte",
  "24/7", "round the clock", "nationwide scale", "global scale", "at massive scale",
];
// Unverifiable effort/ownership claims. Each one asserts something about HOW the work was
// done that no profile bullet supports, and each is the kind of line an interviewer probes.
const OVERCLAIM_PATTERNS: RegExp[] = [
  /\bspent (?:years|a decade|decades)\b/i,
  /\bsingle[- ]handedly\b/i,
  /\bfrom the ground up\b/i,
  /\bbuilt .{0,40}\bfrom scratch\b/i,
  /\bmentor(?:ed|ing)? (?:junior|graduate|new) (?:engineer|developer|dev)/i,
  /\bmission[- ]critical\b/i,
  /\bevery day for (?:years|over)\b/i,
];

/** True if `text` claims a risky tech that does NOT appear in the grounding `source`. */
export function introducesUngroundedTech(text: string, source: string): boolean {
  return ungroundedTech(text, source).length > 0;
}

// Naming a technology is only a lie when it is claimed. COVER_SYS explicitly permits owning a
// gap ("React is the one item I'd be picking up on the job"), and that sentence must not be
// rejected as a fabrication — otherwise the guard punishes the most honest letter the model
// can write. A term is exonerated only when EVERY sentence mentioning it is framed as a gap.
const GAP_CUES =
  /\b(?:no|not|never|n't|nothing)\b|\b(?:gap|learn|learning|pick(?:ing)? up|new to|unfamiliar|yet to|would be|short step|rather than)\b/i;

/**
 * The risky technologies `text` claims that the grounding `source` never mentions, e.g.
 * ["react"]. Reported rather than collapsed to a boolean so a rejection can name the lie.
 */
export function ungroundedTech(text: string, source: string): string[] {
  const sentences = text.split(/(?<=[.!?])\s+|\n+/).filter((s) => s.trim());
  return RISKY_TECH.filter((_, i) => {
    const re = RISKY_TECH_RE[i]!;
    if (!re.test(text) || re.test(source)) return false;
    const mentions = sentences.filter((s) => re.test(s));
    // Every mention framed as a gap => an honest admission, not a claim of experience.
    return !(mentions.length > 0 && mentions.every((s) => GAP_CUES.test(s)));
  });
}

/**
 * True if `text` states a metric the grounding `source` does not. Every number that reads as
 * a claim (percentages, multipliers, counts, money, year spans) must be traceable to the
 * profile — the model reliably invents plausible-sounding figures, and an invented metric on
 * a resume or cover letter is the single most damaging kind of hallucination in this pipeline.
 *
 * Small bare integers (<= 10, e.g. "a few", "3 short paragraphs", ".NET 8") are ignored:
 * they are almost always prose or a version number, not an evidence claim.
 */
export function introducesUngroundedNumbers(text: string, source: string): boolean {
  return ungroundedNumbers(text, source).length > 0;
}

/**
 * The specific figures in `text` that `source` does not support, e.g. ["18+", "thousands"].
 * Reported rather than collapsed to a boolean so a rejection can name what was made up.
 */
export function ungroundedNumbers(text: string, source: string): string[] {
  const found: string[] = [];
  const src = source.toLowerCase().replace(/,/g, "");
  // Letterhead furniture carries digits that are not claims about the candidate: the date
  // line we inject ourselves ("11 August 2026"), URLs, and the phone number. Scrub them
  // before scanning, or every letter is rejected for the date at the top of it.
  const t = text
    .toLowerCase()
    .replace(
      /\b\d{1,2}\s+(?:january|february|march|april|may|june|july|august|september|october|november|december)\s+\d{4}\b/g,
      " ",
    )
    .replace(/https?:\/\/\S+|\b[\w.-]+\.(?:com|nz|org|io|co)\S*/g, " ")
    .replace(/\b0\d[\d\s-]{7,}\b/g, " "); // NZ phone number

  for (const w of SCALE_WORDS) if (t.includes(w) && !src.includes(w)) found.push(w);

  // Percentages, money, multipliers and standalone counts, each with its unit attached so
  // "60%" is not matched by a bare "60" elsewhere in the source.
  const claims = t.replace(/,/g, "").match(/\d+(?:\.\d+)?\s*(?:%|x\b|k\b|m\b|\+)|\$\s?\d[\d.]*/g) ?? [];
  const flatSrc = src.replace(/\s+/g, "");
  for (const raw of claims) {
    const claim = raw.replace(/\s+/g, "");
    if (flatSrc.includes(claim)) continue;
    // "20+" is the standard resume rendering of a source that states 20 years, and "60%+"
    // of one that states 60% — accept the trailing "+" when the bare figure is grounded.
    //
    // The bare figure has to match as a NUMBER, not as a substring. `flatSrc.includes("12")`
    // is true for a master containing "2012", "2026" or an 021 phone number, which is how an
    // invented "12+ years" passed this guard on a master that states no years at all. Digit
    // boundaries on both sides keep "12" from matching inside a longer number.
    if (claim.endsWith("+")) {
      // Claims are matched from `\d+(?:\.\d+)?` so the bare figure is digits and at most one
      // dot — the only character needing escaping before it goes into a RegExp.
      const bare = claim.slice(0, -1).replace(/\./g, "\\.");
      if (new RegExp(`(?<!\\d)${bare}(?!\\d)`).test(src)) continue;
    }
    found.push(claim);
  }

  // Bare counts big enough to read as evidence ("24,300 files", "50 engineers", "20 years").
  const counts = t.replace(/,/g, "").match(/\b\d{2,}\b/g) ?? [];
  for (const c of counts) {
    if (Number(c) <= 10) continue;
    if (/^(19|20)\d{2}$/.test(c)) continue; // calendar years are safe (dates, "2009 systems")
    if (!src.includes(c)) found.push(c);
  }
  return [...new Set(found)];
}

/** True if `text` makes an unverifiable effort/ownership claim the `source` does not support. */
export function makesOverclaim(text: string, source: string): boolean {
  return OVERCLAIM_PATTERNS.some((re) => re.test(text) && !re.test(source));
}

export function hasBannedPhrase(text: string): boolean {
  const t = text.toLowerCase();
  return BANNED_PHRASES.some((p) => t.includes(p));
}

/**
 * A generated doc is shippable only if every claim in it is traceable to the candidate's own
 * source material: no invented technology, no invented metric, no unverifiable effort claim,
 * and no cliché tell. Anything that fails falls back to deterministic, truthful content.
 */
export function isGroundedAndClean(text: string, source: string): boolean {
  return failedGuards(text, source).length === 0;
}

/**
 * Which guards a draft trips, by name. Same checks as isGroundedAndClean, but reported
 * rather than collapsed to a boolean, so a rejection in the logs says WHY the model's
 * draft was thrown away instead of leaving a silent fallback to explain.
 */
export function failedGuards(text: string, source: string): string[] {
  const numbers = ungroundedNumbers(text, source);
  const tech = ungroundedTech(text, source);
  const checks: [string, boolean][] = [
    [`ungrounded-tech (${tech.join(", ")})`, tech.length > 0],
    [`ungrounded-numbers (${numbers.join(", ")})`, numbers.length > 0],
    ["overclaim", makesOverclaim(text, source)],
    ["banned-phrase", hasBannedPhrase(text)],
  ];
  return checks.filter(([, hit]) => hit).map(([name]) => name);
}

/**
 * Deterministic, truthful cover letter assembled from the master frontmatter + the user's own
 * fallback wording. Used whenever the model's letter is unreliable (ungrounded tech, cliché
 * tells) or the model is offline. Reads cleanly without any model help.
 */
function buildFallbackCover(job: Job, fm: Record<string, any>, fallbackNote = ""): string {
  const company = job.company || "your team";
  const role = job.title || "the role";
  const contact = [
    String(fm.name || "").trim(),
    String(fm.location || "").trim(),
    [fm.phone, fm.email].filter(Boolean).join(" | "),
    String(fm.linkedin || "").trim(),
  ].filter(Boolean).join("\n");

  const software = isDevRole(headTitle(job));
  const vars = fallbackVars(role, company, fm);
  const fromVault = renderFallbackSection(fallbackNote, software ? "Software role" : "Other role", vars);

  return [
    contact,
    "",
    todayLong(),
    "",
    "The Hiring Team",
    company,
    "",
    "Dear Hiring Manager,",
    "",
    ...(fromVault ?? (software ? devFallbackBody(vars) : offTrackFallbackBody(vars))),
    "",
    "Kind regards,",
    String(fm.name || "").trim(),
    "",
  ].join("\n");
}

/** Values a fallback body may use, as `{{name}}` placeholders in the vault note. */
type FallbackVars = Record<"role" | "company" | "location" | "town" | "tagline" | "drivers_licence", string>;

function fallbackVars(role: string, company: string, fm: Record<string, any>): FallbackVars {
  const location = String(fm.location || "").trim();
  const tagline = String(fm.tagline || "").trim().replace(/[.\s]+$/, "");
  return {
    role,
    company,
    location,
    // "Nelson, Tasman, New Zealand" → "Nelson": the line reads "I'm local to …".
    town: location.split(",")[0]?.trim() ?? "",
    tagline,
    drivers_licence: String(fm.drivers_licence || "").trim().replace(/^Full /, "full "),
  };
}

/**
 * The candidate's own fallback wording, from Career/Profile/cover-letter-fallback.md:
 *
 *   ## Software role
 *   I'm a senior developer, and the {{role}} role at {{company}} …
 *
 *   ## Other role
 *   I'd like to be considered for the {{role}} role at {{company}}. … I'm local to {{town}} …
 *
 * Career facts are personal, so they live in the vault next to the master resume rather than
 * in this file. A line whose placeholder has no value (no licence in the master, say) is
 * dropped whole instead of printing a gap. Returns null when the note or section is absent,
 * and the generic bodies below are used instead.
 */
function renderFallbackSection(note: string, heading: string, vars: FallbackVars): string[] | null {
  const body = section(matter(note || "").content, heading);
  if (!body) return null;
  const lines: string[] = [];
  for (const line of body.split(/\r?\n/)) {
    let empty = false;
    const filled = line.replace(/\{\{\s*(\w+)\s*\}\}/g, (_m, key: string) => {
      const v = (vars as Record<string, string>)[key] ?? "";
      if (!v) empty = true;
      return v;
    });
    if (!empty) lines.push(filled.trimEnd());
  }
  // Collapse the blank runs left by dropped lines, and trim the ends.
  const out = lines.join("\n").replace(/\n{3,}/g, "\n\n").trim();
  return out ? out.split("\n") : null;
}

/**
 * Generic fallback body for a software role, used when the vault has no fallback note. It
 * states nothing beyond the master's own tagline and location: without the candidate's own
 * wording there is no safe way to describe their career, and the resume carries the detail.
 */
function devFallbackBody(v: FallbackVars): string[] {
  return [
    `I'd like to be considered for the ${v.role} role at ${v.company}.`,
    ...(v.tagline ? ["", `${v.tagline}.`] : []),
    "",
    `My resume sets out the detail, and I'd welcome the chance to talk through how my experience fits ${v.company}.${v.town ? ` I'm based in ${v.town} and available at short notice.` : ""}`,
  ];
}

/**
 * Generic fallback body for a job from a search track — courier, driver, warehouse, retail,
 * local IT. These are deliberately off-profile, so the main career is NOT evidence of fit and
 * must never be presented as it. The old single-template fallback interpolated the title into
 * a sentence claiming the role matched the candidate's software work, which for a
 * Storeperson ad scored 5/100 read as a straight non-sequitur to the person holding it.
 *
 * So this branch claims nothing about the work itself. It owns the change of work in one line,
 * offers only what genuinely transfers to any job, and keeps it short — a warehouse manager
 * is not reading four hundred words. Anything more specific has to come from the model, or
 * from the candidate writing it themselves in the vault note.
 */
function offTrackFallbackBody(v: FallbackVars): string[] {
  const extras = [
    v.drivers_licence ? `I hold a ${v.drivers_licence}` : "",
    "I'm used to following process and safety instructions exactly as written",
    "and I'm well past basic computer skills",
  ].filter(Boolean);
  return [
    `I'd like to be considered for the ${v.role} role at ${v.company}.`,
    "",
    "I'll be straight that this is different work from my last role. I'm applying for it on its own terms. What I'd bring is what any team needs from a new starter: I turn up, I follow a process carefully, I pick up a new system quickly, and I'm comfortable with the paperwork and computer side of a job.",
    "",
    `${extras.join(", ")}.`,
    "",
    v.town
      ? `I'm local to ${v.town}, available now, and would be glad to come in and talk.`
      : "I'm available now and would be glad to come in and talk.",
  ];
}

/** Today's date, NZ long form e.g. "9 June 2026". */
function todayLong(): string {
  return new Date().toLocaleDateString("en-NZ", { day: "numeric", month: "long", year: "numeric" });
}

/** Replace template tokens the model may have left unfilled, with safe values. */
function fillPlaceholders(md: string, job: Job, contact: Record<string, any> = {}): string {
  const today = todayLong();
  return (
    md
      .replace(/\{\{\s*(date|today)\s*\}\}/gi, today)
      .replace(/\{\{\s*(company|employer)\s*\}\}/gi, job.company || "the company")
      .replace(/\{\{\s*(job[_\s-]?title|role|position)\s*\}\}/gi, job.title || "the role")
      .replace(/\{\{\s*location\s*\}\}/gi, job.location || "")
      .replace(/\{\{\s*(hiring_manager[_a-z]*|recipient|name)\s*\}\}/gi, "The Hiring Team")
      .replace(/\{\{\s*salutation\s*\}\}/gi, "Hiring Manager")
      // Anything still left: drop the raw token so {{x}} never reaches the user.
      .replace(/\{\{\s*[^}]*\}\}/g, "")
      // Bracketed placeholders the model sometimes emits: fill known contact ones from
      // the master frontmatter, then drop any remaining "[Your ...]" tokens.
      .replace(/\[\s*your\s+name\s*\]/gi, String(contact.name || ""))
      .replace(/\[\s*your\s+(phone|phone\s+number)\s*\]/gi, String(contact.phone || ""))
      .replace(/\[\s*your\s+(email|email\s+address)\s*\]/gi, String(contact.email || ""))
      .replace(/\[\s*your\s+linkedin[^\]]*\]/gi, String(contact.linkedin || ""))
      .replace(/\[\s*your\s+github[^\]]*\]/gi, String(contact.github || ""))
      .replace(/\[\s*your\s+(location|address)\s*\]/gi, String(contact.location || ""))
      .replace(/\[\s*your[^\]]*\]/gi, "")
  );
}

/**
 * Normalise common US -ize/-yze spellings to UK -ise/-yse for NZ resumes. Only rewrites a
 * curated stem list, so safe words like "size", "prize", "capsize" are never touched.
 */
function ukSpelling(s: string): string {
  const ize =
    /\b(special|modern|optim|organ|real|recogn|priorit|standard|custom|util|summar|categor|normal|central|maxim|minim|emphas|digit|formal|final|initial|tailor)(ize|izes|ized|izing|ization|izations)\b/gi;
  const suffixMap: Record<string, string> = {
    ize: "ise", izes: "ises", ized: "ised", izing: "ising",
    ization: "isation", izations: "isations",
  };
  return s
    .replace(ize, (_m, stem: string, suf: string) => stem + (suffixMap[suf.toLowerCase()] ?? suf))
    .replace(/\banaly(z)(e|es|ed|ing)\b/gi, (_m, _z, tail: string) => `analys${tail}`);
}

/**
 * Build the contact header from the master frontmatter.
 *
 * The professional title under the name is ALWAYS the master resume's own `role` and is never
 * replaced by the advertised job title. Mirroring the JD title looked like an ATS win, but it
 * retitles the person: applying to a "Solutions Architect" ad printed "Solutions Architect"
 * under the name of a resume whose whole history is development work, which reads as a claim
 * the experience does not back. The JD's wording still reaches the ATS through the summary,
 * the skills section and the cover letter, where it is a description of the work rather than
 * an identity claim.
 */
function buildContactHeader(fm: Record<string, any>): string {
  const name = String(fm.name || "").trim();
  const role = String(fm.role || "").trim();
  const tagline = String(fm.tagline || "").trim();
  const contactBits = [
    fm.location ? `Location: ${fm.location}` : "",
    fm.phone ? `Phone: ${fm.phone}` : "",
  ].filter(Boolean);
  const linkBits = [
    fm.email ? `Email: ${fm.email}` : "",
    fm.linkedin ? `LinkedIn: ${fm.linkedin}` : "",
    fm.github ? `GitHub: ${fm.github}` : "",
  ].filter(Boolean);

  const workRights = String(fm.work_rights || "").trim();

  const lines = [name ? `# ${name}` : "# Resume"];
  if (role) lines.push(`**${role}**`);
  if (tagline) lines.push("", `*${tagline}*`);
  if (contactBits.length) lines.push("", contactBits.join(" | "));
  if (linkBits.length) lines.push(linkBits.join(" | "));
  if (workRights) lines.push(`**${workRights}**`);
  return lines.join("\n");
}

/** Drop the master resume's own header (everything before the first "## " section). */
function stripMasterHeader(body: string): string {
  const i = body.indexOf("\n## ");
  return i >= 0 ? body.slice(i + 1).trim() : body.trim();
}

/**
 * A human-readable job detail file saved alongside the tailored docs. ASCII-folded like the
 * documents themselves: the scraped description carries the job board's curly quotes and
 * em dashes, and this file sits in the same folder the user copies text out of.
 */
function jobDetailDoc(job: Job, score?: Score): string {
  const date = new Date().toISOString().slice(0, 10);
  const doc = [
    frontmatter(job, "job-detail"),
    `# ${job.title}${job.company ? ` - ${job.company}` : ""}`,
    ``,
    `- **Source:** ${job.source}`,
    `- **Company:** ${job.company || "-"}`,
    `- **Location:** ${job.location || "-"}`,
    `- **Salary:** ${job.salaryText || "-"}`,
    `- **Engagement:** ${job.engagement}`,
    score ? `- **Fit:** ${score.fit}/100` : ``,
    `- **Posting:** [${job.url}](${job.url})`,
    `- **Saved:** ${date}`,
    ``,
    `## Full description`,
    ``,
    job.description || "_(description not captured)_",
    ``,
  ].filter((l) => l !== ``).join("\n") + "\n";
  return asciiOnly(doc);
}

function frontmatter(job: Job, type: string): string {
  return asciiOnly([
    `---`,
    `type: ${type}`,
    `job: "${job.title.replace(/"/g, "'")}"`,
    `company: "${(job.company ?? "").replace(/"/g, "'")}"`,
    `source: ${job.source}`,
    `url: ${job.url}`,
    `generated: ${new Date().toISOString()}`,
    `---`,
    ``,
    ``,
  ].join("\n"));
}

/** Append a job-opportunity block (info + links to the generated docs) to the vault file. */
async function appendOpportunity(
  job: Job,
  score: Score | undefined,
  slug: string,
  tailored: boolean,
): Promise<void> {
  await fs.mkdir(vault.jobsDir, { recursive: true });
  await ensureHeader();

  const existing = await readSafe(OPPORTUNITIES_FILE);
  if (existing.includes(`<!-- id:${job.id} -->`)) return; // already logged

  // Opportunities file lives in Jobs/; applications live in Jobs/Applications/<slug>/.
  const rel = `./Applications/${slug}`;
  const date = new Date().toISOString().slice(0, 10);

  const block = [
    ``,
    `## ${job.title}${job.company ? ` — ${job.company}` : ""} <!-- id:${job.id} -->`,
    ``,
    score ? `- **Fit:** ${score.fit}/100${tailored ? "" : "  ·  ⚠️ docs not tailored (Ollama offline)"}` : ``,
    `- **Source:** ${job.source}  ·  **Location:** ${job.location || "—"}  ·  **Salary:** ${job.salaryText || "—"}`,
    `- **Posting:** [${job.url}](${job.url})`,
    `- **Saved:** ${date}`,
    score?.rationale ? `- **Why:** ${score.rationale}` : ``,
    `- 📋 Job detail: [${slug}/job.md](${rel}/job.md)`,
    `- 📄 Resume: [${slug}/resume.md](${rel}/resume.md)`,
    `- ✉️ Cover letter: [${slug}/cover-letter.md](${rel}/cover-letter.md)`,
    ``,
  ].filter((l) => l !== ``).join("\n") + "\n";

  await fs.appendFile(OPPORTUNITIES_FILE, block, "utf8");
}

async function ensureHeader(): Promise<void> {
  const existing = await readSafe(OPPORTUNITIES_FILE);
  if (existing.trim()) return;
  const header = [
    `---`,
    `type: job-opportunities`,
    `updated: ${new Date().toISOString().slice(0, 10)}`,
    `---`,
    ``,
    `# Job Opportunities`,
    ``,
    `Jobs you marked **Interested**. Each entry links to a tailored resume + cover letter`,
    `in \`Career/Jobs/Applications/\`. Newest appended at the bottom.`,
    ``,
  ].join("\n");
  await fs.writeFile(OPPORTUNITIES_FILE, header, "utf8");
}

async function readSafe(p: string): Promise<string> {
  try {
    return await fs.readFile(p, "utf8");
  } catch {
    return "";
  }
}

function errMsg(e: unknown): string {
  return e instanceof Error ? e.message : String(e);
}
