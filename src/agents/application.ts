function jobBlockOf(job: Job): string {
  return [
    `JOB:`,
    `Title: ${job.title}`,
    `Company: ${job.company ?? ""}`,
    `Location: ${job.location ?? ""}`,
    `Salary: ${job.salaryText ?? ""}`,
    `Description:`,
    (job.description || "").slice(0, 8000),
  ].join("\n");
}

/** Model rewrites ONLY the Professional Summary paragraph, grounded in the master resume. */
export async function tailorSummary(job: Job, masterBody: string): Promise<string> {
  const masterSummary = extractSection(masterBody, "Professional Summary");
  const out = await ollamaChat(
    SUMMARY_SYS,
    `MASTER RESUME (for grounding — use only facts from here):\n${masterBody}\n\nMASTER SUMMARY (the paragraph to re-angle):\n${masterSummary || "(none)"}\n\n${jobBlockOf(job)}`,
    // Thinking is OFF, and that is a measured decision rather than the old default. Enabling
    // it on qwen3:32b was tried against the real vault prompt on 2026-08-31: it took 307s
    // versus 50s, and the richer prose it produced invented "12+ years of experience" for a
    // master that states no years figure at all — which the (now-fixed) numbers guard throws
    // away, leaving the untailored master summary. Slower AND a worse result. The `think`
    // option and its budget/timeout handling stay in place so this can be re-measured on a
    // future model, but the default earns its keep as it is.
    { maxTokens: 700, temperature: 0.3 },
  );
  // Keep only prose: drop any <think> block (qwen3), heading/bullets the model may add,
  // collapse to a paragraph.
  const clean = out
    .replace(/<think>[\s\S]*?<\/think>/gi, "")
    .replace(/```[a-zA-Z]*\n?/g, "")
    .replace(/```/g, "")
    .replace(/^\s*#+.*$/gm, "")
    .replace(/^\s*[-*+]\s+/gm, "")
    .trim();
  // Guard: if the model returned junk or something suspiciously short, signal failure.
  if (clean.length < 80) throw new Error("summary too short");
  // Guard: reject a summary that fabricates tech (e.g. Azure/Salesforce) or uses cliché tells,
  // so the caller falls back to the master's own (truthful) summary.
  const failed = failedGuards(clean, masterBody);
  if (failed.length) throw new Error(`summary tripped ${failed.join(", ")}`);
  return clean;
}

/** Model writes the cover letter from the template + profile + job. */
export async function tailorCover(job: Job, profile: Profile): Promise<string> {
  return ollamaChat(
    COVER_SYS,
    `Today's date: ${todayLong()}.\n\nCOVER LETTER TEMPLATE:\n${profile.coverLetterTemplate}\n\nPROFILE:\n${profile.skills}\n${profile.experience}\n\n${jobBlockOf(job)}`,
    // Thinking off, for the reasons on tailorSummary above. The budget is still well clear of
    // the ~1200-token letter so a long one is never truncated mid-sentence.
    { maxTokens: 1600, temperature: 0.7 },
  );
}

/**
 * Build the resume body deterministically from the master: copy every section verbatim,
 * swapping only the Professional Summary paragraph for the tailored one (if we got a good
 * one). Guarantees a complete, placeholder-free, truthful resume regardless of model quality.
 */
function assembleResume(masterBody: string, tailoredSummary: string): string {
  if (!tailoredSummary.trim()) return masterBody.trim();
  return replaceSection(masterBody, "Professional Summary", tailoredSummary.trim()).trim();
}

/** Return the body text under a "## <name>" heading (excluding the heading), or "" if absent. */
export function extractSection(body: string, name: string): string {
  const re = new RegExp(`^##\\s+${escapeRe(name)}\\s*$`, "im");
  const m = re.exec(body);
  if (!m) return "";
  const start = m.index + m[0].length;
  const rest = body.slice(start);
  const next = rest.search(/^##\s+/m);
  return (next >= 0 ? rest.slice(0, next) : rest).trim();
}

/** Replace the body under a "## <name>" heading with new content; keep heading + all else. */
function replaceSection(body: string, name: string, content: string): string {
  const re = new RegExp(`^(##\\s+${escapeRe(name)}\\s*)$`, "im");
  const m = re.exec(body);
  if (!m) return body; // section not found — leave master untouched
  const headEnd = m.index + m[0].length;
  const rest = body.slice(headEnd);
  const next = rest.search(/^##\s+/m);
  const after = next >= 0 ? rest.slice(next) : "";
  return `${body.slice(0, headEnd)}\n\n${content}\n\n${after}`.replace(/\n{3,}/g, "\n\n");
}

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// --- JD-focused tailoring (select + order existing master content) -----------
//
// The weak local model is never trusted to WRITE resume content (it fabricates tech and
// drops sections). Instead it only makes STRUCTURED CHOICES over content that already
// exists in the master — which skill categories are relevant, what order bullets go in —
// returned as JSON we validate against the known set. Code then reassembles verbatim
// master text in the chosen order. Any parse/validation failure returns the section
// unchanged, so tailoring can sharpen focus but can never invent or lose a fact.

/** JD signal for tailoring: the target title plus the skills the scorer matched/flagged. */
function jdHints(job: Job, score?: Score): string {
  const skills = [...(score?.matchedSkills ?? []), ...(score?.missingSkills ?? [])];
  return [
    `Target role: ${job.title}`,
    skills.length ? `Skills the job emphasises: ${skills.join(", ")}` : "",
  ].filter(Boolean).join("\n");
}

/** The JD's title with any trailing qualifier ("- Fixed Term", "(Part Time)") stripped. */
function headTitle(job: Job): string {
  return String(job.title || "").split(/[-–—|(/]/)[0]!.trim();
}

/**
 * True when the job title reads like a genuine engineering role. Search tracks deliberately
 * surface off-profile local work (courier, driver, warehouse, retail), so anything that
 * assumes the software career applies has to check this first.
 */
function isDevRole(title: string): boolean {
  return /develop|engineer|architect|integration|software|programmer|devops|\bsre\b|platform|back.?end|full.?stack/i.test(
    title,
  );
}

interface SkillCategory {
  label: string;
  block: string;
}

/**
 * Split a skills-style section into labelled entries. Handles both the Core Competencies
 * form ("- **Label:** …") and the Technical Skills form ("**Label:** …", blank-separated).
 */
function parseCategories(section: string): SkillCategory[] {
  const head = /^\s*(?:[-*+]\s+)?\*\*(.+?):\*\*/;
  const cats: SkillCategory[] = [];
  let cur: SkillCategory | null = null;
  for (const line of section.split("\n")) {
    const m = head.exec(line);
    if (m) {
      if (cur) cats.push(cur);
      cur = { label: m[1]!.trim(), block: line };
    } else if (cur) {
      cur.block += "\n" + line;
    }
  }
  if (cur) cats.push(cur);
  return cats.map((c) => ({ ...c, block: c.block.replace(/\n+$/, "") }));
}

const FOCUS_SYS = `You re-order a candidate's resume skill categories to match a JOB.
You are given a list of category LABELS and the JOB. Return ONLY JSON:
{"order":[<labels most relevant to this job first>]}
Use the EXACT label strings provided. Include every label with clear relevance to the job and
omit labels with no relevance. NEVER invent a label. No commentary, no markdown, JSON only.`;

/** Ask the model to rank the given labels by relevance to the job. Returns known labels only. */
async function rankLabels(labels: string[], job: Job, hints: string): Promise<string[]> {
  const raw = await ollamaChat(
    FOCUS_SYS,
    `LABELS:\n${labels.map((l, i) => `${i + 1}. ${l}`).join("\n")}\n\n${hints}\n\n${jobBlockOf(job)}`,
    { json: true, maxTokens: 300, temperature: 0.2 },
  );
  const parsed = JSON.parse(raw);
  const order: string[] = Array.isArray(parsed?.order) ? parsed.order.map(String) : [];
  const known = new Set(labels);
  const seen = new Set<string>();
  return order.filter((l) => known.has(l) && !seen.has(l) && (seen.add(l), true));
}

/**
 * Re-order a labelled skills section so JD-relevant categories come first. For the big
 * Technical Skills "wall" we also TRIM to just the relevant categories (when the model
 * gives a confident set) — focus beats completeness on a per-job resume. Core Competencies
 * is short and all-signal, so it is re-ordered but never trimmed.
 */
async function reorderCatSection(
  body: string,
  name: string,
  job: Job,
  hints: string,
  trim: boolean,
  floor: string[] = [],
): Promise<string> {
  const section = extractSection(body, name);
  if (!section.trim()) return body;
  const cats = parseCategories(section);
  if (cats.length < 3) return body; // too few to bother re-ordering
  let picked: string[];
  try {
    picked = await rankLabels(cats.map((c) => c.label), job, hints);
  } catch {
    return body; // model unreachable or returned junk — keep master section
  }
  if (picked.length < 2) return body; // weak signal — don't reshuffle on a guess
  const byLabel = new Map(cats.map((c) => [c.label, c]));
  const front = picked.map((l) => byLabel.get(l)!).filter(Boolean);
  const rest = cats.filter((c) => !picked.includes(c.label));
  let chosen: SkillCategory[];
  if (trim && picked.length >= 4) {
    // Trim to the picked set, but guarantee floor categories survive even if the model
    // didn't rank them (e.g. core Languages / Architecture the JD implies but never lists).
    const have = new Set(front.map((c) => c.label));
    const kept = cats.filter((c) => floor.includes(c.label) && !have.has(c.label));
    chosen = [...front, ...kept];
  } else {
    chosen = [...front, ...rest]; // re-order only, keep every category
  }
  const sep = name === "Technical Skills" ? "\n\n" : "\n";
  return replaceSection(body, name, chosen.map((c) => c.block).join(sep));
}

/** Re-focus both skills sections toward the job (Core Competencies re-ordered; the
 *  Technical Skills wall re-ordered and trimmed to the relevant categories, with a floor
 *  of always-keep categories so a core skill is never dropped on a per-job copy). */
async function focusSkills(job: Job, body: string, hints: string): Promise<string> {
  let out = body;
  out = await reorderCatSection(out, "Core Competencies", job, hints, false);
  out = await reorderCatSection(out, "Technical Skills", job, hints, true, [
    "Languages & Frameworks",
    "Architecture & Patterns",
  ]);
  return out;
}

const ORDER_SYS = `You re-order a candidate's resume bullet points to best match a JOB.
Given a numbered list of BULLETS and the JOB, return ONLY JSON:
{"order":[<all bullet numbers, most relevant first>]}
Include EVERY number exactly once (a permutation of the numbers shown, 1-based). Do not add,
drop, merge, or rewrite bullets. No commentary, no markdown, JSON only.`;

/**
 * Re-order the top-level bullets under "## <name>" so the most JD-relevant come first,
 * keeping every bullet verbatim and every non-bullet line in place. The model returns a
 * permutation of indices; anything that is not a strict permutation leaves the section as-is.
 */
async function reorderBulletSection(
  body: string,
  name: string,
  job: Job,
  hints: string,
): Promise<string> {
  const section = extractSection(body, name);
  if (!section.trim()) return body;
  const lines = section.split("\n");
  const bulletIdx: number[] = [];
  lines.forEach((l, i) => {
    if (/^\s*[-*+]\s+/.test(l)) bulletIdx.push(i);
  });
  const n = bulletIdx.length;
  if (n < 3) return body;
  const bullets = bulletIdx.map((i) => lines[i]!);
  let order: number[];
  try {
    const raw = await ollamaChat(
      ORDER_SYS,
      `BULLETS:\n${bullets
        .map((b, i) => `${i + 1}. ${b.replace(/^\s*[-*+]\s+/, "")}`)
        .join("\n")}\n\n${hints}\n\n${jobBlockOf(job)}`,
      { json: true, maxTokens: 200, temperature: 0.2 },
    );
    const p = JSON.parse(raw);
    order = Array.isArray(p?.order) ? p.order.map((x: any) => Number(x) - 1) : [];
  } catch {
    return body;
  }
  // Must be a strict permutation of 0..n-1, else we don't trust it — keep master order.
  if (order.length !== n || order.some((x) => !Number.isInteger(x) || x < 0 || x >= n)) return body;
  if (new Set(order).size !== n) return body;
  const reordered = order.map((o) => bullets[o]!);
  const newLines = [...lines];
  bulletIdx.forEach((li, k) => {
    newLines[li] = reordered[k]!;
  });
  return replaceSection(body, name, newLines.join("\n"));
}

